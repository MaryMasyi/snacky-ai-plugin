#import libraries
import pandas as pd
import numpy as np
from scipy.sparse import csr_matrix
from sklearn.metrics.pairwise import cosine_similarity
import joblib
import os

os.makedirs('models', exist_ok=True)

# Load the cleaned user-product interactions table
user_product = pd.read_csv('data/cleaned_weighted_user_product.csv')
print(f"Loaded user-product pairs: {len(user_product):,}")

# Build sparse matrix (users × products)
# Create a sparse matrix of user–product purchase counts for collaborative filtering
# Each row represents a user, each column represents a product,
# and the values indicate how many times that user purchased that product.
# Use sparse matrix to be memory-efficient because most entries are zero (most users don’t buy most products).

print("\nBuilding sparse matrix...")

unique_users = user_product['user_id'].unique()
unique_products = user_product['product_id'].unique()
user_to_idx = {uid: i for i, uid in enumerate(unique_users)}
product_to_idx = {pid: j for j, pid in enumerate(unique_products)}

rows = user_product['user_id'].map(user_to_idx).values
cols = user_product['product_id'].map(product_to_idx).values
data = user_product['purchase_weight'].values

matrix_sparse = csr_matrix((data, (rows, cols)),
                           shape=(len(unique_users), len(unique_products)))

print(f"Sparse matrix shape: {matrix_sparse.shape[0]:,} users × {matrix_sparse.shape[1]:,} products")
print(f"Non-zero entries: {matrix_sparse.nnz:,}")

# Filter products by reasonable minimum number of buyers, at least 5 users count
# To remove unpopular products
print("\nFiltering products with ≥5 users...")

min_users = 5
product_popularity = np.bincount(matrix_sparse.indices, minlength=matrix_sparse.shape[1])
popular_mask = product_popularity >= 5
popular_indices = np.where(popular_mask)[0]
matrix_filtered = matrix_sparse[:, popular_indices]
popular_product_ids = [unique_products[i] for i in popular_indices]
print(f"Kept {len(popular_product_ids)} products with ≥{min_users} users")

# Build recommended system based on products similarity
# Compute item-item cosine similarity

print("\nComputing item-item cosine similarity...")
item_matrix_sparse = matrix_filtered.T
item_sim_dense = cosine_similarity(item_matrix_sparse)
item_sim_df = pd.DataFrame(
    item_sim_dense,
    index=popular_product_ids,
    columns=popular_product_ids
)
print(f"Similarity matrix shape: {item_sim_df.shape}")

# Generate top-5 recommendations for each product
print("\nGenerating recommendations...")
def get_top_n(pid, sim_df, n=5):
    if pid not in sim_df.columns:
        return []
    return sim_df[pid].sort_values(ascending=False).drop(pid).head(n).index.tolist()

recommendations = {pid: get_top_n(pid, item_sim_df) for pid in popular_product_ids}
print(f"Recommendations generated for {len(recommendations)} products")

# Build recommendation system for new user when there is no information about their preference
# Top-20 popular products fallback

print("\nCreating popular products fallback...")
purchase_sums = np.array(matrix_filtered.sum(axis=0)).flatten()
top_indices = np.argsort(-purchase_sums)[:20]
popular_products_list = [popular_product_ids[i] for i in top_indices]
print(f"Top 20 popular products saved")

# Load product names
product_names_df = pd.read_csv('data/snack_product_names.csv')
# Product name mapping
product_names = dict(zip(product_names_df['product_id'], product_names_df['product_name']))

# Save all models

joblib.dump(recommendations, 'models/snack_recommendations.pkl')
joblib.dump(popular_products_list, 'models/snack_popular_products.pkl')
joblib.dump(product_names, 'models/snack_product_names.pkl')
joblib.dump(item_sim_df, 'models/snack_item_similarity.pkl')

print("\nAll models saved to 'models/'")

# Model Evaluation
sample = popular_products_list[0] if popular_products_list else None
if sample:
    sample_name = product_names.get(sample, "Unknown")
    recs = recommendations.get(sample, [])[:3]
    rec_names = [product_names.get(r, "Unknown") for r in recs]
    print(f"\nTest product: {sample_name}")
    print(f"Top recommendations: {rec_names}")
else:
    print("No popular products found.")