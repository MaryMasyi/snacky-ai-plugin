#import libraries
import pandas as pd
import numpy as np
import xgboost as xgb
from sklearn.model_selection import GridSearchCV
from sklearn.metrics import classification_report, roc_auc_score, confusion_matrix
import joblib
import shap
import matplotlib.pyplot as plt
import os

# Create directories
os.makedirs('models', exist_ok=True)
os.makedirs('plots', exist_ok=True)

# Load preprocessed  data
X_train = joblib.load('data/processed/X_train.pkl')
X_test = joblib.load('data/processed/X_test.pkl')
y_train = joblib.load('data/processed/y_train.pkl')
y_test = joblib.load('data/processed/y_test.pkl')
encoders = joblib.load('data/processed/encoders.pkl')

print(f"Training samples: {X_train.shape[0]}")
print(f"Test samples: {X_test.shape[0]}")
print(f"Train abandonment rate: {y_train.mean():.2%}")
print(f"Test abandonment rate: {y_test.mean():.2%}")

# Feature list (for SHAP and importance)
features = X_train.columns.tolist()
print(f"\nFeatures used: {features}")

# Hyperparameter tuning with GridSearchCV

param_grid = {
    'max_depth': [4, 6, 8],
    'learning_rate': [0.05, 0.1],
    'n_estimators': [100, 150],
    'subsample': [0.8, 1.0]
}

xgb_model = xgb.XGBClassifier(random_state=42, use_label_encoder=False, eval_metric='logloss')
grid_search = GridSearchCV(
    xgb_model, param_grid, cv=5, scoring='roc_auc', n_jobs=-1, verbose=1
)
grid_search.fit(X_train, y_train)

best_model = grid_search.best_estimator_
print(f"\nBest parameters: {grid_search.best_params_}")
print(f"Best cross-validation AUC: {grid_search.best_score_:.4f}")

# Evaluation on test set

y_pred = best_model.predict(X_test)
y_proba = best_model.predict_proba(X_test)[:, 1]

print("\n--- Evaluation Results ---")
print(classification_report(y_test, y_pred))
print(f"AUC-ROC: {roc_auc_score(y_test, y_proba):.4f}")
print("\nConfusion Matrix:")
print(confusion_matrix(y_test, y_pred))

# Feature Importance

feature_importance = pd.DataFrame({
    'feature': features,
    'importance': best_model.feature_importances_
}).sort_values('importance', ascending=False)

print("\n--- Top 10 Features ---")
print(feature_importance.head(10))

# Plot feature importance
plt.figure(figsize=(10,6))
plt.barh(feature_importance.head(10)['feature'], feature_importance.head(10)['importance'], color='teal')
plt.xlabel('Importance')
plt.title('Top 10 Feature Importances (XGBoost)')
plt.gca().invert_yaxis()
plt.tight_layout()
plt.savefig('plots/feature_importance.png')
plt.show()
print("Saved: plots/feature_importance.png")

# SHAP Explainability

sample_size = min(200, X_test.shape[0])
X_sample = X_test.sample(sample_size, random_state=42)
explainer = shap.TreeExplainer(best_model)
shap_values = explainer.shap_values(X_sample)

# Summary plot
shap.summary_plot(shap_values, X_sample, feature_names=features, show=False)
plt.tight_layout()
plt.savefig('plots/shap_summary.png')
plt.show()
print("Saved: plots/shap_summary.png")

# Save the final model
joblib.dump(best_model, 'models/xgboost_abandonment.pkl')
print("\n✅ Model saved to 'models/xgboost_abandonment.pkl'")